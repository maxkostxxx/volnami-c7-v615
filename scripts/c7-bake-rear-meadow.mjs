// Exact byte mask only: no quantization beyond the existing author calculation.
import { rearMeadowOwnerAt } from '../lab/c7-scene/terrain.js'
import * as T from 'three'
import { readFile, writeFile } from 'node:fs/promises'
import { gzipSync } from 'node:zlib'
import { createHash } from 'node:crypto'
const sha = bytes => createHash('sha256').update(bytes).digest('hex')
const width=320,height=290,data=new Uint8Array(width*height)
for(let j=0;j<height;j++)for(let i=0;i<width;i++)data[j*width+i]=Math.round(255*T.MathUtils.clamp(rearMeadowOwnerAt(-155+(i+.5)/width*160,-420+(j+.5)/height*145),0,1))
const record={width,height,sourceSha256:sha(await readFile('lab/c7-scene/terrain.js')),sha256:sha(data),gzipBase64:gzipSync(data,{level:9}).toString('base64')}
await writeFile('lab/c7-scene/rear-meadow-data.js','// Generated by scripts/c7-bake-rear-meadow.mjs; validated when packaging.\nexport const rearMeadowData = '+JSON.stringify(record)+';\n')
console.log({width,height,bytes:data.length,gzipBytes:Buffer.from(record.gzipBase64,'base64').length,sha256:record.sha256})
