// Lossless alternatives to the existing gzip bodies. Never rebakes scene data.
import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {gunzipSync,brotliCompressSync,brotliDecompressSync,constants} from 'node:zlib';
const root=process.argv[2]??'lab/c7-scene',hash=b=>createHash('sha256').update(b).digest('hex'),records={};
for(const name of ['terrain-cache/geometry.bin.gz','startup-data/fields.bin.gz','mobile-data/sky-data.gz','mobile-data/left-sky-data.gz','sky-data/field.rgba16f.gz','left-sky-data/field.rgba16f.gz']){
 const gzip=await fs.readFile(path.join(root,name)),raw=gunzipSync(gzip);
 const brotli=brotliCompressSync(raw,{params:{[constants.BROTLI_PARAM_QUALITY]:11,[constants.BROTLI_PARAM_LGWIN]:24}});
 if(!brotliDecompressSync(brotli).equals(raw))throw Error('Transport roundtrip failed: '+name);
 const alternative=name.replace(/\.gz$/,'.br');
 await fs.writeFile(path.join(root,alternative),brotli);
 records['./'+name]={file:'./'+alternative,bytes:brotli.length,sha256:hash(brotli),gzipSha256:hash(gzip),rawBytes:raw.length,rawSha256:hash(raw)};
 console.log({name,gzip:gzip.length,brotli:brotli.length});
}
await fs.writeFile(path.join(root,'binary-transports.js'),'// Generated by scripts/c7-bake-binary-transports.mjs; exact existing payloads.\nexport const binaryTransports='+JSON.stringify(records,null,2)+';\n');
