export type NavItem = { label: string; href: string }

export type ProcessStep = {
  title: string
  /** У четвёртого шага описания нет намеренно — это смысловая точка полосы. */
  description?: string
}

export type Service = {
  index: number
  title: string
  lead: string
  items: string[]
  closing: string
}

export type CaseBlock =
  | { kind: 'lead'; text: string }
  | {
      kind: 'section'
      heading: string
      paragraphs?: string[]
      items?: string[]
      subsections?: { heading: string; text: string }[]
    }
  | { kind: 'group'; title: string; blocks: CaseBlock[] }

export type CaseVisual = {
  /** Путь от /public */
  src: string
  alt: string
  width: number
  height: number
}

export type Case = {
  slug: string
  title: string
  /**
   * Короткое описание для карточки на главной.
   * ЭТО ДОСЛОВНАЯ ВЫДЕРЖКА из текста самого кейса, а не пересказ.
   * Собственных формулировок тут быть не может: в ТЗ коротких описаний
   * нет, а выдумывать их запрещено. Если карточке нужен текст короче —
   * обрезать визуально (line-clamp), а не переписывать словами.
   */
  teaser: string
  blocks: CaseBlock[]
  visuals: CaseVisual[]
  /** Текста нет — карточку не выдумывать. */
  pending?: boolean
  externalLink?: { label: string; href: string }
}

